/**
 * Generate local stand-in photographs for the visual comparison.
 *
 * WHY
 * ---
 * The approved baseline references seven Unsplash photographs by URL. This
 * environment's network policy denies `images.unsplash.com`, so both the
 * prototype and the implementation render their missing-media fallbacks and
 * the *normal* state — the one with photography in it — never gets compared.
 *
 * These files are **not** the baseline photographs and are not presented as
 * them. They are neutral, deterministic placeholders at the same slot ids, so
 * that both sides receive an identical image byte-for-byte and any difference
 * that shows up is layout: slot aspect ratio, crop behaviour, rounding,
 * overlay placement, caption position. Photographic fidelity is not being
 * tested here and cannot be, in this environment.
 *
 * Each file is written under the photo id with no extension, because the
 * baseline requests it as `<id>?fm=jpg&w=…&h=…` and a static file server
 * strips the query. The bytes are a real JPEG, so browsers sniff it correctly.
 *
 * Run:  node scripts/make-review-photos.mjs [out-dir]
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';

const OUT = process.argv[2] ?? '/tmp/kkl-prototype-review/vendor/photos';

/** The seven slots the baseline credits, with a distinct hue each. */
const SLOTS = [
  { id: 'photo-1750762367188-2f884520d63d', slot: 'hero', hue: 212 },
  { id: 'photo-1759882611054-fa61e7fa3099', slot: 'a', hue: 189 },
  { id: 'photo-1755103114153-eb0a66e3725a', slot: 'b', hue: 146 },
  { id: 'photo-1757970326337-95d7cca56fa1', slot: 'c', hue: 33 },
  { id: 'photo-1758193431351-68538bf55ec3', slot: 'd', hue: 267 },
  { id: 'photo-1762344692227-f6496e80d7bf', slot: 'e', hue: 8 },
  { id: 'photo-1755735340764-3b077cab0c5c', slot: 'f', hue: 96 },
];

/** A 3:2 image at the largest size any slot asks for; CSS does the cropping. */
const W = 1600;
const H = 1100;

function svg({ slot, hue }) {
  // Bands rather than a smooth wash: a gradient hides crop differences, and
  // crop behaviour is exactly what this comparison needs to show.
  const bands = Array.from({ length: 6 }, (_, i) =>
    `<rect x="0" y="${(H / 6) * i}" width="${W}" height="${H / 6}" `
    + `fill="hsl(${hue} 38% ${76 - i * 7}%)"/>`).join('');
  return Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">`
    + bands
    // Corner marks make it obvious at a glance when a slot has cropped an edge.
    + `<g fill="none" stroke="hsl(${hue} 60% 22%)" stroke-width="10">`
    + `<path d="M40 40 h160 M40 40 v160"/><path d="M${W - 40} 40 h-160 M${W - 40} 40 v160"/>`
    + `<path d="M40 ${H - 40} h160 M40 ${H - 40} v-160"/>`
    + `<path d="M${W - 40} ${H - 40} h-160 M${W - 40} ${H - 40} v-160"/></g>`
    + `<circle cx="${W / 2}" cy="${H / 2}" r="150" fill="hsl(${hue} 55% 30%)" opacity="0.85"/>`
    + `<text x="${W / 2}" y="${H / 2 - 8}" font-family="sans-serif" font-size="96" `
    + `font-weight="700" fill="#fff" text-anchor="middle">${slot.toUpperCase()}</text>`
    + `<text x="${W / 2}" y="${H / 2 + 58}" font-family="sans-serif" font-size="30" `
    + `fill="#fff" text-anchor="middle" opacity="0.9">STAND-IN</text>`
    + `<text x="${W / 2}" y="${H - 60}" font-family="sans-serif" font-size="34" `
    + `fill="hsl(${hue} 60% 20%)" text-anchor="middle">`
    + `not the baseline photograph</text></svg>`,
  );
}

mkdirSync(OUT, { recursive: true });
for (const entry of SLOTS) {
  const jpeg = await sharp(svg(entry)).jpeg({ quality: 78 }).toBuffer();
  // No extension: the requested URL carries a query string the server strips.
  writeFileSync(join(OUT, entry.id), jpeg);
  writeFileSync(join(OUT, `${entry.id}.jpg`), jpeg);
}
writeFileSync(join(OUT, 'README.txt'),
  'Generated by scripts/make-review-photos.mjs. These are placeholders, not\n'
  + 'the baseline photographs. They exist so the normal (image present) state\n'
  + 'can be compared at all where images.unsplash.com is unreachable.\n');
console.log(`${SLOTS.length} stand-in photographs written to ${OUT}`);
