/**
 * Generates docs/phase-2/coverage.md from the screen map and the approved
 * inventory, so the matrix cannot drift from what the rig actually captures.
 *
 * `docs/phase-2/inventory.json` is the 113 rows parsed out of
 * `KKL Phase 1 - Screen Inventory.dc.html` at kkl-design 5bc3512 — id, group,
 * name, route and states, exactly as the approved document declares them.
 *
 * Run:  node scripts/build-coverage-matrix.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { PAIRS, NESTED, LIBRARY } from './screen-map.mjs';

const OUT = 'docs/phase-2/coverage.md';
const VISUAL = 'docs/phase-2/visual';
const inventory = JSON.parse(readFileSync('docs/phase-2/inventory.json', 'utf8'));

const pairById = new Map(PAIRS.map((p) => [p.id, p]));
const nestedById = new Map(NESTED.map((n) => [n.id, n]));
const libraryById = new Map(LIBRARY.map((l) => [l.id, l]));

const index = existsSync(`${VISUAL}/index.json`)
  ? JSON.parse(readFileSync(`${VISUAL}/index.json`, 'utf8'))
  : [];
const captured = new Map();
for (const row of index) {
  if (!row.ok) continue;
  if (!captured.has(row.id)) captured.set(row.id, []);
  captured.get(row.id).push(row.width);
}

const geometry = {};
for (const w of [1440, 390]) {
  const f = `${VISUAL}/geometry-${w}.json`;
  if (existsSync(f)) {
    for (const r of JSON.parse(readFileSync(f, 'utf8'))) {
      geometry[r.id] ??= {};
      geometry[r.id][w] = r.score ?? 0;
    }
  }
}

const rows = [];
let pairs = 0, nested = 0, library = 0, missing = 0;

for (const item of inventory) {
  const pair = pairById.get(item.id);
  const nest = nestedById.get(item.id);
  const lib = libraryById.get(item.id);

  if (pair) {
    pairs += 1;
    const widths = captured.get(item.id) ?? [];
    const g = geometry[item.id] ?? {};
    const files = widths.map((w) => `\`${VISUAL}/${item.id}-${w}-*.png\``).join('<br>');
    const score = [1440, 390].filter((w) => w in g).map((w) => `${w}: ${g[w]}`).join(', ');
    rows.push({
      id: item.id, name: item.name, kind: 'Pair',
      evidence: files || '**not captured**',
      widths: widths.length ? widths.join(', ') : '—',
      detail: score ? `divergence ${score}` : 'not measured',
    });
    if (!widths.length) missing += 1;
  } else if (nest) {
    nested += 1;
    rows.push({
      id: item.id, name: item.name, kind: `Nested in ${nest.within}`,
      evidence: `\`${nest.evidence}\``,
      widths: 'via parent',
      detail: nest.note,
    });
  } else if (lib) {
    library += 1;
    rows.push({
      id: item.id, name: item.name, kind: 'Library',
      evidence: `\`${lib.evidence}\``,
      widths: lib.context,
      detail: 'Shared component evidence, judged in the screen context named',
    });
  } else {
    missing += 1;
    rows.push({ id: item.id, name: item.name, kind: '**UNMAPPED**', evidence: '—', widths: '—', detail: 'No evidence mapped. This is a gap.' });
  }
}

const body = `# Phase 2 — coverage matrix

Every row of the approved screen inventory (\`KKL Phase 1 - Screen Inventory.dc.html\`,
kkl-design \`5bc3512\`), mapped to the evidence that covers it.

**Generated by \`scripts/build-coverage-matrix.mjs\`** from \`screen-map.mjs\` and
\`inventory.json\`, so it cannot drift from what the rig captures. Do not edit by
hand.

## How to read it

| Kind | Meaning |
|---|---|
| **Pair** | A prototype screen and an application route, captured side by side at the widths shown |
| **Nested in X** | A state inside another screen. The approved design has no separate screen for it, so building one would contradict the design; the parent's pair carries the layout and the named suite carries the behaviour |
| **Library** | C-01..C-12 — shared components, not screens. Covered by component evidence, judged in the screen context named |

\`divergence\` is the geometry differ's score for that screen: typography
mismatches weighted 2, structural mismatches 5, on text both sides render
identically. **It is a filter for where to look, not a verdict.** Zero means
the measured properties agree; it says nothing about spacing, alignment or
anything the tool cannot see.

## Totals

| | Count |
|---|---|
| Inventory rows | ${inventory.length} |
| Covered by a captured pair | ${pairs - missing} |
| Covered as a nested state | ${nested} |
| Covered as library evidence | ${library} |
| **Not covered** | **${missing}** |

## The matrix

| ID | Screen | Kind | Widths | Evidence | Notes |
|---|---|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${r.name} | ${r.kind} | ${r.widths} | ${r.evidence} | ${r.detail} |`).join('\n')}

## What this matrix does not claim

- **Photographic fidelity.** The image-present state is compared with generated
  stand-ins; the baseline's own photographs cannot be fetched in this
  environment. See \`visual/README.md\`.
- **That a zero score is a pass.** The differ compares measured properties of
  matched text and controls. Spacing, alignment, shadow and imagery are outside
  it, and a screen with no divergence still needs a person to look at the pair.
- **Anything about a real backend.** Every screen here renders sample services.
`;

writeFileSync(OUT, body);
console.log(`${OUT}: ${inventory.length} rows — ${pairs - missing} pairs, ${nested} nested, ${library} library, ${missing} uncovered.`);
if (missing) process.exit(1);
